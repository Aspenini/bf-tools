#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn covers_every_printable_character() {
        assert_eq!(GLYPHS.len(), (LAST - FIRST + 1) as usize);
    }

    #[test]
    fn space_is_blank_and_letters_are_not() {
        assert_eq!(glyph(b' '), &[0; HEIGHT]);
        assert_ne!(glyph(b'A'), &[0; HEIGHT]);
    }

    #[test]
    fn glyphs_stay_inside_five_pixels() {
        for (index, glyph) in GLYPHS.iter().enumerate() {
            for row in glyph {
                assert_eq!(
                    row & !0x1F,
                    0,
                    "glyph {:?} has a pixel outside five columns",
                    (FIRST + index as u8) as char
                );
            }
        }
    }

    #[test]
    fn bytes_outside_the_range_draw_as_a_box() {
        assert_eq!(glyph(0x00), &FALLBACK);
        assert_eq!(glyph(0xFF), &FALLBACK);
        assert_eq!(glyph(0x1F), &FALLBACK);
    }
}
