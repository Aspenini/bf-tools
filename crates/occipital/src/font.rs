//! The built-in 5x7 text font.
//!
//! One entry per printable ASCII character from [`FIRST`] to [`LAST`], seven
//! scanlines each, five pixels wide with bit 4 leftmost. Anything outside that
//! range draws as [`FALLBACK`], a hollow box, so a stray byte stays visible
//! rather than being silently dropped.
//!
//! This is the font the Game Boy Advance runtime used, kept when the Cranelift
//! port removed that target.

/// Height of every glyph, in scanlines.
pub const HEIGHT: usize = 7;

/// Width of every glyph, in pixels.
pub const WIDTH: usize = 5;

/// First character the font covers.
pub const FIRST: u8 = 0x20;

/// Last character the font covers.
pub const LAST: u8 = 0x7E;

/// Drawn in place of any byte the font does not cover.
pub const FALLBACK: [u8; HEIGHT] = [0x1F, 0x11, 0x15, 0x11, 0x15, 0x11, 0x1F];

/// Return the glyph for `byte`, or [`FALLBACK`] if there is not one.
pub fn glyph(byte: u8) -> &'static [u8; HEIGHT] {
    if !(FIRST..=LAST).contains(&byte) {
        return &FALLBACK;
    }
    &GLYPHS[(byte - FIRST) as usize]
}

